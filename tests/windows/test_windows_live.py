"""The Windows app of a product from `forge app new --windows` (S72, S73), built for real: its
client generated by Kiota from the server's snapshot, its tests run, and the app published with
.NET 10 and the Windows App SDK and packed by Velopack into the installer, the ZIP and the update
files the product's website offers, plain and selling on the website.

Marked `fullstack` and only for Windows: it needs the .NET 10 SDK and NuGet. CI's `windows-app`
job runs it: `uv run pytest -m fullstack tests/windows -v`.
"""

import json
import os
import shutil
import subprocess
import zipfile
from pathlib import Path
from typing import NoReturn

import pytest

from forge.app_template import write_app

pytestmark = [
    pytest.mark.fullstack,
    pytest.mark.skipif(os.name != "nt", reason="a WinUI 3 app builds on Windows only"),
]


def unavailable(reason: str) -> NoReturn:
    """Skip when a tool is missing; CI sets FULLSTACK_REQUIRE_ALL so nothing is skipped there."""
    if os.environ.get("FULLSTACK_REQUIRE_ALL"):
        pytest.fail(reason)
    pytest.skip(reason)


def run(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    """Run a command and fail the test with its output when it fails."""
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True, timeout=1800,
                            check=False)  # fmt: skip
    assert result.returncode == 0, f"{' '.join(command)}\n{result.stdout[-8000:]}\n{result.stderr}"
    return result


@pytest.fixture(scope="module", params=[(), ("payments",)], ids=["plain", "paid"])
def windows_app(tmp_path_factory: pytest.TempPathFactory, request: pytest.FixtureRequest) -> Path:
    """The Windows app of a fresh product, plain or selling on the website."""
    if shutil.which("dotnet") is None:
        unavailable("the .NET SDK is not installed (dotnet)")
    folder = tmp_path_factory.mktemp("windows") / "tally"
    write_app(folder, "tally", features=("windows", *request.param))
    return folder / "windows"


def test_the_client_is_generated_and_the_tests_pass(windows_app: Path) -> None:
    run(["dotnet", "test", "Tests/Tests.csproj", "-c", "Release"], windows_app)
    assert (windows_app / "Core" / "Api" / "ApiClient.cs").is_file()


def test_the_app_is_packed_into_an_installer_a_zip_and_updates(windows_app: Path) -> None:
    run(["dotnet", "tool", "restore"], windows_app)
    run(["dotnet", "publish", "App/App.csproj", "-c", "Release", "-p:Platform=x64",
         "-p:RuntimeIdentifier=win-x64", "-o", "publish"], windows_app)  # fmt: skip
    assert (windows_app / "publish" / "Tally.exe").is_file()
    run(["dotnet", "tool", "run", "vpk", "pack", "--packId", "Tally", "--packVersion", "1.0.7",
         "--packDir", "publish", "--mainExe", "Tally.exe", "--packTitle", "Tally",
         "--icon", "App/App.ico", "--runtime", "win-x64", "--delta", "None",
         "--outputDir", "releases"], windows_app)  # fmt: skip
    releases = windows_app / "releases"
    assert (releases / "Tally-win-Setup.exe").read_bytes()[:2] == b"MZ"
    with zipfile.ZipFile(releases / "Tally-win-Portable.zip") as portable:
        assert "Update.exe" in portable.namelist()
    listed = json.loads((releases / "releases.win.json").read_text(encoding="utf-8"))
    assert [(a["Version"], a["FileName"]) for a in listed["Assets"]] == [
        ("1.0.7", "Tally-1.0.7-full.nupkg")
    ]
