const de: Texts = { ...coreDe, ...adminDe, ...appleDe, ...releaseDe, ...listingDe };

export type TextKey = keyof Texts;

function pick(): Texts {
  const lang = typeof navigator === "undefined" ? "en" : navigator.language.toLowerCase();
  return lang.startsWith("de") ? de : en;
}

const texts = pick();

/** "de" or "en": the language the texts are in. */
export const language: "de" | "en" = texts === de ? "de" : "en";

export function t(key: TextKey, values: Record<string, string> = {}): string {
  return texts[key].replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? `{${name}}`);
}
