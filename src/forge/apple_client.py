"""The Apple app of a full-stack product (S70): the app from `forge apple new`, plus a client of
the product's server, generated from its OpenAPI snapshot by Apple's swift-openapi-generator and
pointed at staging. An app that sells digital goods sells them with StoreKit 2 (App Store Review
Guideline 3.1.1), and its client has no web checkout.

The client is generated by running the generator as a command (`apple/generate-api.sh`, on a
Mac), not as an Xcode build plug-in: Xcode asks a person before it runs a package's plug-in, and
Forge does not answer that question for them. The generated files are committed like the
server's snapshot they come from.
"""

import plistlib

from forge.apple_template import app_files

PACKAGES = """\
packages:  # what the generated client of the server's API (Shared/API) needs to run
  OpenAPIRuntime:
    url: https://github.com/apple/swift-openapi-runtime
    from: 1.7.0
  OpenAPIURLSession:
    url: https://github.com/apple/swift-openapi-urlsession
    from: 1.0.2
"""
USES = "      - package: OpenAPIRuntime\n      - package: OpenAPIURLSession\n"
APP_SOURCES = "    sources: [Shared]\n"
WEB_TAGS = ("payments",)  # sold through Apple instead when the app sells digital goods

GENERATOR_CONFIG = """\
# swift-openapi-generator's settings. generate-api.sh reads the server's snapshot,
# ../server/openapi.json, and writes the client to Shared/API.
generate:
  - types
  - client
accessModifier: internal
"""
STORE_FILTER = """\
# The app sells digital goods with StoreKit 2 (Shared/Store.swift), never with the web checkout
# (App Store Review Guideline 3.1.1): the client leaves out every operation tagged {web}.
filter:
  tags: [{tags}]
"""

GENERATE_SH = """\
#!/bin/sh
# Writes the client of the server's API (Shared/API) from ../server/openapi.json with Apple's
# swift-openapi-generator. Run it on a Mac (`sh generate-api.sh`) after every change of
# openapi.json, build, and commit the result together with the snapshot.
set -eu
cd "$(dirname "$0")"
mkdir -p Shared/API
swift run --package-path APIGenerator swift-openapi-generator generate \\
    --config openapi-generator-config.yaml \\
    --output-directory Shared/API \\
    ../server/openapi.json
"""

GENERATOR_PACKAGE = """\
// swift-tools-version: 5.9
// The generator generate-api.sh runs; the app itself does not depend on this package.
import PackageDescription

let package = Package(
    name: "APIGenerator",
    platforms: [.macOS(.v13)],
    dependencies: [
        .package(url: "https://github.com/apple/swift-openapi-generator", from: "1.7.0"),
    ],
    targets: [.target(name: "APIGenerator")]  // empty: SwiftPM wants one to run the generator
)
"""
EMPTY_SWIFT = (
    "// Nothing here: this package only pins the generator that ../../generate-api.sh runs.\n"
)
SANDBOX = "        com.apple.security.app-sandbox: true  # the Mac App Store requires the sandbox\n"
NETWORK = "        com.apple.security.network.client: true  # the app talks to its server\n"

API_SERVER_SWIFT = """\
import Foundation

/// Where the product's server runs. Every release goes to staging first; the App Store build
/// talks to production. The client itself is generated into Shared/API (../generate-api.sh):
/// `Client(serverURL: APIServer.staging, transport: URLSessionTransport())`.
enum APIServer {{
    static let staging = URL(string: "{staging}")!
    static let production = URL(string: "{production}")!
}}
"""

STORE_SWIFT = """\
import Observation
import StoreKit

/// In-app purchases with StoreKit 2: an iPhone app sells digital goods through Apple (App Store
/// Review Guideline 3.1.1), never through a web checkout. Add the products in App Store
/// Connect with these ids; the server learns of purchases from Apple's notifications.
@MainActor
@Observable
final class Store {{
    static let productIDs = ["{bundle}.pro"]

    private(set) var products: [Product] = []
    private(set) var purchased: Set<String> = []

    /// Loads the products and what was bought, then follows purchases made elsewhere.
    func start() async {{
        products = (try? await Product.products(for: Self.productIDs)) ?? []
        for await result in Transaction.currentEntitlements {{
            await take(result)
        }}
        for await result in Transaction.updates {{
            await take(result)
        }}
    }}

    func buy(_ product: Product) async throws {{
        if case .success(let result) = try await product.purchase() {{
            await take(result)
        }}
    }}

    /// Apple's signed word for a purchase; unverified ones unlock nothing.
    private func take(_ result: VerificationResult<Transaction>) async {{
        guard case .verified(let transaction) = result else {{ return }}
        if transaction.revocationDate == nil {{
            purchased.insert(transaction.productID)
        }} else {{
            purchased.remove(transaction.productID)
        }}
        await transaction.finish()
    }}
}}
"""

README = """
## The server's API

`APIServer.swift` says where the product's server runs (staging, then production). The client of
its API is generated from `../server/openapi.json` into `Shared/API` by Apple's
swift-openapi-generator: run `sh generate-api.sh` on a Mac after every change of the snapshot,
build, and commit both. The generator runs as a command, not as an Xcode plug-in, so Xcode never
has to be told to trust a plug-in.
"""
STORE_README = """
## In-app purchases

The app sells digital goods with StoreKit 2 (`Shared/Store.swift`), as Apple requires (App Store
Review Guideline 3.1.1); its API client has no web checkout. Create the products named in
`Store.productIDs` in App Store Connect before the first review.
"""


def client_files(
    name: str, bundle_id: str, urls: tuple[str, str], api_tags: list[str], digital_goods: bool
) -> dict[str, bytes]:
    """The product's Apple app by its path inside the product's `apple/` folder (`urls`: the
    server on staging and in production; `api_tags`: the tags of the API's operations)."""
    files = app_files(name, bundle_id)
    files["project.yml"] = with_api_packages(files["project.yml"].decode()).encode()
    config = GENERATOR_CONFIG
    if digital_goods:
        tags = ", ".join(sorted(t for t in api_tags if t not in WEB_TAGS))
        config += STORE_FILTER.format(web=", ".join(WEB_TAGS), tags=tags)
        files["Shared/Store.swift"] = STORE_SWIFT.format(bundle=bundle_id).encode()
    files["openapi-generator-config.yaml"] = config.encode()
    files["generate-api.sh"] = GENERATE_SH.encode()
    files["APIGenerator/Package.swift"] = GENERATOR_PACKAGE.encode()
    files["APIGenerator/Sources/APIGenerator/Empty.swift"] = EMPTY_SWIFT.encode()
    files[f"macOS/{name}.entitlements"] = plistlib.dumps(
        {"com.apple.security.app-sandbox": True, "com.apple.security.network.client": True}
    )
    staging, production = urls
    server = API_SERVER_SWIFT.format(staging=staging, production=production)
    files["Shared/APIServer.swift"] = server.encode()
    files[".gitignore"] += b"APIGenerator/.build/\n"
    files["README.md"] += (README + (STORE_README if digital_goods else "")).encode()
    return files


def with_api_packages(spec: str) -> str:
    """project.yml with the API client's packages, used by every app target."""
    spec = spec.replace("\ntargets:\n", "\n" + PACKAGES + "targets:\n", 1)
    spec = spec.replace(SANDBOX, SANDBOX + NETWORK, 1)
    lines = spec.splitlines(keepends=True)
    out: list[str] = []
    for at, line in enumerate(lines):
        out.append(line)
        if line != APP_SOURCES:
            continue
        if lines[at + 1] == "    dependencies:\n":  # the iPhone app: after its Watch app
            lines[at + 2] += USES
        else:
            out.append("    dependencies:\n" + USES)
    return "".join(out)
